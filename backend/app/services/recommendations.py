"""D6 DISTRIBOX - Recommendation Engine.

Turns channel analytics into a prioritised list of actions, each one
carrying the arithmetic that justifies it.

Three rules this module obeys without exception
-----------------------------------------------
1. **No LLM.** Recommendations are produced by explicit, readable rules
   over observed numbers. A language model could *phrase* a
   recommendation later; it never decides what the recommendation is or
   what it claims.
2. **Every claim is checkable.** ``evidence`` on each recommendation
   contains the actual figures that triggered the rule, formatted from the
   data - never a plausible-sounding sentence.
3. **Observation and projection are labelled separately.**
   ``evidence_type`` is ``OBSERVED`` when the finding is arithmetic on
   recorded bookings, ``MODELLED_ESTIMATE`` when it depends on a
   conversion assumption, and ``SCENARIO_ASSUMPTION`` when it depends on
   a counterfactual scenario. A reader can always tell which they are
   looking at.

``confidence`` describes how much weight the *evidence* deserves. It is
never a probability that the action will succeed.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal
from typing import Any, Dict, List, Optional

from app.analytics.channel_analytics import PortfolioAnalytics
from app.core.money import ZERO, quantize_money, quantize_rate
from app.services.scenario_engine import ScenarioAssumptions, ScenarioOutcome

__all__ = [
    "Recommendation",
    "RecommendationEngine",
    "OBSERVED",
    "MODELLED_ESTIMATE",
    "SCENARIO_ASSUMPTION",
]

OBSERVED = "OBSERVED"
MODELLED_ESTIMATE = "MODELLED_ESTIMATE"
SCENARIO_ASSUMPTION = "SCENARIO_ASSUMPTION"

CHANNEL_MIX = "CHANNEL_MIX"
DIRECT_CONVERSION = "DIRECT_CONVERSION"
CANNIBALIZATION = "CANNIBALIZATION"
COST_REDUCTION = "COST_REDUCTION"


@dataclass(frozen=True)
class Recommendation:
    category: str
    title: str
    evidence: str
    assumption: Optional[str]
    expected_impact: Optional[str]
    confidence: str
    evidence_type: str
    priority: int
    channel_code: Optional[str] = None
    #: The action itself, stated separately from the finding.
    #:
    #: ``title`` is what the data shows; ``action`` is what to do about it.
    #: Keeping them apart matters because a card that mixes "OTA Alpha takes
    #: 24% of bookings for 20% of net revenue" with "renegotiate the
    #: commission" invites the reader to treat the observation as the
    #: instruction. It is generated by the same rule that produced the
    #: finding, so the action can never drift from the evidence.
    action: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "category": self.category,
            "title": self.title,
            "action": self.action,
            "evidence": self.evidence,
            "assumption": self.assumption,
            "expected_impact": self.expected_impact,
            "confidence": self.confidence,
            "evidence_type": self.evidence_type,
            "priority": self.priority,
            "channel_code": self.channel_code,
        }


def _inr(value: Decimal) -> str:
    """Format rupees with Indian digit grouping (lakh/crore aware)."""
    return f"Rs {value:,.2f}"


def _pct(value: Decimal) -> str:
    return f"{value * 100:.2f}%"


class RecommendationEngine:
    """Deterministic rule set over observed analytics. Stateless."""

    #: A channel needs at least this share of portfolio distribution cost
    #: before its cost structure is worth a negotiation.
    MATERIALITY_FLOOR = Decimal("0.02")

    #: Below this net ADR advantage, "move volume direct" is noise.
    MIN_NET_ADR_GAIN = Decimal("250")

    def generate(
        self,
        portfolio: PortfolioAnalytics,
        assumptions: Optional[ScenarioAssumptions] = None,
        scenario: Optional[ScenarioOutcome] = None,
    ) -> List[Recommendation]:
        """Run every rule, merge, and sort by priority (highest first)."""
        recs: List[Recommendation] = []
        recs.extend(self._cost_reduction(portfolio))
        recs.extend(self._cannibalization(portfolio))
        recs.extend(self._direct_conversion(portfolio, assumptions))
        recs.extend(self._channel_mix(portfolio, scenario))
        recs.sort(key=lambda r: (-r.priority, r.category, r.title))
        return recs

    # -- rule 1: renegotiate the channels that cost the most -----------

    def _cost_reduction(self, portfolio: PortfolioAnalytics) -> List[Recommendation]:
        out: List[Recommendation] = []
        total_cost = portfolio.total_distribution_cost
        if total_cost <= 0:
            return out

        for c in portfolio.ranked_by_distribution_cost():
            share_of_cost = c.distribution_cost / total_cost
            if share_of_cost < self.MATERIALITY_FLOOR:
                continue

            gap = portfolio.share_gap(c.channel_code) or Decimal("0")
            commission_share = (
                c.commission_amount / c.distribution_cost
                if c.distribution_cost > 0
                else Decimal("0")
            )

            if gap > Decimal("0.01"):
                title = (
                    f"Renegotiate {c.channel_name} commission - it takes "
                    f"{_pct(c.booking_share)} of bookings but returns only "
                    f"{_pct(c.net_revenue_share)} of net revenue"
                )
                confidence = "HIGH"
            else:
                title = (
                    f"{c.channel_name} absorbs {_pct(c.distribution_cost_pct)} of gross "
                    f"revenue in distribution cost - review contract terms"
                )
                confidence = "MEDIUM"

            out.append(
                Recommendation(
                    category=COST_REDUCTION,
                    title=title,
                    action=(
                        f"Open a commercial review of the {c.channel_name} contract. "
                        f"Commission is {_pct(commission_share)} of this channel's "
                        f"distribution cost, so renegotiating the rate is the largest "
                        f"single lever; the alternatives are a deeper rate/card "
                        f"discount structure or moving volume to direct. Test any "
                        f"change in the Channel Mix Simulator before committing "
                        f"inventory."
                    ),
                    evidence=(
                        f"{c.booking_count:,} bookings, {c.room_nights:,} room nights, "
                        f"{_inr(c.gross_revenue)} gross. "
                        f"Distribution cost {_inr(c.distribution_cost)} "
                        f"({_pct(c.distribution_cost_pct)} of gross; "
                        f"{_pct(share_of_cost)} of the hotel's total distribution cost). "
                        f"Commission {_inr(c.commission_amount)} "
                        f"({_pct(commission_share)} of that cost), "
                        f"discount {_inr(c.discount_amount)}, "
                        f"payment fees {_inr(c.payment_fee)}, "
                        f"other {_inr(c.other_channel_cost)}. "
                        f"Net revenue {_inr(c.net_revenue)}; "
                        f"net ADR {_inr(c.net_adr)} vs gross ADR {_inr(c.gross_adr)} "
                        f"(ADR penalty {_inr(c.net_adr_penalty)}/night). "
                        f"Booking share {_pct(c.booking_share)}, "
                        f"net revenue share {_pct(c.net_revenue_share)}, "
                        f"share gap {_pct(gap)}."
                    ),
                    assumption=(
                        "Assumes a commission reduction is negotiable at all. "
                        "No contractual term has been verified."
                    ),
                    expected_impact=(
                        f"A 1 percentage-point reduction in the effective commission "
                        f"rate on this channel's gross revenue is worth "
                        f"{_inr(quantize_money(c.gross_revenue * Decimal('0.01')))} "
                        f"net, holding volume constant."
                    ),
                    confidence=confidence,
                    evidence_type=OBSERVED,
                    priority=self._priority(share_of_cost),
                    channel_code=c.channel_code,
                )
            )
        return out

    # -- rule 2: direct bookings costing what OTAs cost ----------------

    def _cannibalization(self, portfolio: PortfolioAnalytics) -> List[Recommendation]:
        out: List[Recommendation] = []
        direct = [c for c in portfolio.channels if c.is_direct]
        indirect = [c for c in portfolio.channels if not c.is_direct]
        if not direct or not indirect:
            return out

        d = max(direct, key=lambda c: c.net_adr)
        expensive = [
            c for c in indirect if d.net_adr - c.net_adr >= self.MIN_NET_ADR_GAIN
        ]
        if not expensive:
            return out

        wasted = quantize_money(
            sum(((d.net_adr - c.net_adr) * Decimal(c.room_nights) for c in expensive), ZERO)
        )
        total_cost = portfolio.total_distribution_cost or Decimal("1")
        materiality = min(Decimal("1"), wasted / total_cost)

        top = max(expensive, key=lambda c: (d.net_adr - c.net_adr) * Decimal(c.room_nights))

        out.append(
            Recommendation(
                category=CANNIBALIZATION,
                title=(
                    f"Direct net ADR is {_inr(d.net_adr)}/night - "
                    f"{_inr(d.net_adr - top.net_adr)}/night more than {top.channel_name}"
                ),
                action=(
                    f"Test moving a portion of {top.channel_name} inventory to direct. "
                    f"Run it in the Channel Mix Simulator and read the demand-at-risk "
                    f"figure alongside the gain - the gap between them is the part of "
                    f"this recommendation that is an assumption, not an observation."
                ),
                evidence=(
                    f"{d.channel_name} net ADR {_inr(d.net_adr)} over {d.room_nights:,} "
                    f"room nights (gross ADR {_inr(d.gross_adr)}, distribution cost "
                    f"{_inr(d.distribution_cost)}, i.e. {_pct(d.distribution_cost_pct)} of gross). "
                    f"Against it, {', '.join(c.channel_name for c in expensive)} net ADRs are "
                    f"{', '.join(_inr(c.net_adr) for c in expensive)}. "
                    f"Room nights currently sold through those channels: "
                    f"{sum(c.room_nights for c in expensive):,}. "
                    f"Observed ADR gap on those nights: {_inr(wasted)} - an upper bound "
                    f"on what perfect channel discipline would be worth, NOT a forecast."
                ),
                assumption=(
                    "No assumption that any of those guests would have booked direct. "
                    "The figure states the size of the gap, not that it is capturable."
                ),
                expected_impact=(
                    "Closing even part of this gap is the single largest net revenue "
                    "lever visible in the observed data."
                ),
                confidence="HIGH",
                evidence_type=OBSERVED,
                priority=self._priority(materiality),
                channel_code=top.channel_code,
            )
        )
        return out

    # -- rule 3: modelled direct conversion ----------------------------

    def _direct_conversion(
        self,
        portfolio: PortfolioAnalytics,
        assumptions: Optional[ScenarioAssumptions],
    ) -> List[Recommendation]:
        out: List[Recommendation] = []
        if assumptions is None:
            return out
        direct = [c for c in portfolio.channels if c.is_direct]
        if not direct:
            return out
        d = direct[0]
        d_net_per_night = d.net_adr

        total_cost = portfolio.total_distribution_cost or Decimal("1")

        for c in portfolio.channels:
            if c.is_direct or c.booking_count == 0:
                continue
            conv = assumptions.conversion_for(c.channel_code)
            if conv <= 0:
                continue

            convertible = quantize_rate(Decimal(c.room_nights) * conv)
            gain = quantize_money(convertible * (d_net_per_night - c.net_adr))
            if gain <= 0:
                continue

            materiality = min(Decimal("1"), gain / total_cost)
            out.append(
                Recommendation(
                    category=DIRECT_CONVERSION,
                    title=(
                        f"Convert {_pct(conv)} of {c.channel_name}'s volume to direct - "
                        f"modelled {_inr(gain)} net gain"
                    ),
                    action=(
                        f"Run a direct-booking campaign on {c.channel_name} volume: rate "
                        f"parity, a direct-booking benefit, and a booking-engine nudge on "
                        f"{c.channel_name} pages. Treat {_inr(gain)} as the modelled "
                        f"ceiling under the stated {_pct(conv)} conversion assumption, "
                        f"not as a committed saving."
                    ),
                    evidence=(
                        f"{c.channel_name}: {c.room_nights:,} room nights, "
                        f"net ADR {_inr(c.net_adr)}/night, "
                        f"{_inr(c.net_revenue)} net revenue. "
                        f"Applying the hotel-supplied direct conversion rate of "
                        f"{_pct(conv)} to {c.room_nights:,} nights yields "
                        f"{convertible:,.0f} convertible nights. "
                        f"Direct net ADR is {_inr(d_net_per_night)}/night, a difference of "
                        f"{_inr(d_net_per_night - c.net_adr)}/night, so "
                        f"{convertible:,.0f} x {_inr(d_net_per_night - c.net_adr)} = "
                        f"{_inr(gain)} modelled additional net revenue."
                    ),
                    assumption=(
                        f"Assumes the hotel's stated {_pct(conv)} direct conversion rate "
                        f"for {c.channel_name} holds, and that direct capacity exists to "
                        f"absorb {convertible:,.0f} additional nights. Neither has been "
                        f"verified against booking behaviour."
                    ),
                    expected_impact=_inr(gain),
                    confidence="MEDIUM",
                    evidence_type=MODELLED_ESTIMATE,
                    priority=self._priority(materiality),
                    channel_code=c.channel_code,
                )
            )
        out.sort(key=lambda r: (-r.priority, r.title))
        return out

    # -- rule 4: portfolio-level mix observation -----------------------

    def _channel_mix(
        self,
        portfolio: PortfolioAnalytics,
        scenario: Optional[ScenarioOutcome],
    ) -> List[Recommendation]:
        out: List[Recommendation] = []
        if portfolio.total_bookings == 0:
            return out

        ranked = portfolio.ranked_by_net_revenue()
        top = ranked[0]
        direct_nights = sum(
            c.room_nights for c in portfolio.channels if c.is_direct
        )

        if direct_nights / Decimal(portfolio.total_room_nights or 1) < Decimal("0.20"):
            out.append(
                Recommendation(
                    category=CHANNEL_MIX,
                    title=(
                        f"Direct is only {_pct(safe_share(direct_nights, portfolio.total_room_nights))} "
                        f"of room nights while carrying "
                        f"{_pct(portfolio.direct_net_revenue_share)} of net revenue"
                    ),
                    action=(
                        f"Set a direct-booking target for the coming season and protect "
                        f"rate parity on your own brand. Use the Channel Mix Simulator to "
                        f"test how far direct can realistically absorb volume before "
                        f"changing how much inventory you release to each OTA."
                    ),
                    evidence=(
                        f"Portfolio: {portfolio.total_bookings:,} bookings, "
                        f"{portfolio.total_room_nights:,} room nights, "
                        f"{_inr(portfolio.total_gross_revenue)} gross, "
                        f"{_inr(portfolio.total_distribution_cost)} distribution cost "
                        f"({_pct(portfolio.portfolio_distribution_cost_pct)} of gross), "
                        f"{_inr(portfolio.total_net_revenue)} net. "
                        f"Direct channels take {direct_nights:,} room nights "
                        f"({_pct(portfolio.direct_booking_share)}) but deliver "
                        f"{_pct(portfolio.direct_net_revenue_share)} of net revenue. "
                        f"Best net revenue contributor: {top.channel_name} at "
                        f"{_inr(top.net_revenue)}."
                    ),
                    assumption=(
                        "Descriptive only. Mix share is an observation; any claim about "
                        "what the mix should be requires the scenario assumptions."
                    ),
                    expected_impact=(
                        "Shifting even a few points of volume to direct raises net "
                        "revenue per night; see the scenario comparison for a modelled "
                        "figure."
                    ),
                    confidence="HIGH",
                    evidence_type=OBSERVED,
                    priority=55,
                    channel_code=None,
                )
            )

        if scenario is not None and scenario.is_feasible:
            delta = scenario.net_revenue_delta
            out.append(
                Recommendation(
                    category=CHANNEL_MIX,
                    title=(
                        f"Deterministic scenario reallocation: modelled net revenue "
                        f"{'increase' if delta > 0 else 'decrease'} of {_inr(abs(delta))}"
                    ),
                    action=(
                        f"Reproduce this allocation in the Channel Mix Simulator, then "
                        f"stress it: raise the demand-at-risk assumption and watch the "
                        f"result move. Only commit inventory once the modelled gain "
                        f"survives a pessimistic arrival rate."
                    ),
                    evidence=(
                        f"Scenario '{scenario.name}' moves "
                        f"{len(scenario.moves):,} single-night shifts under the "
                        f"objective {scenario.objective}. "
                        f"Gross {_inr(scenario.gross_revenue)}, "
                        f"distribution cost {_inr(scenario.distribution_cost)} "
                        f"({_pct(scenario.distribution_cost_pct)}), "
                        f"net {_inr(scenario.net_revenue)} vs baseline "
                        f"{_inr(scenario.baseline_net_revenue)}. "
                        f"Modelled lost demand {scenario.estimated_lost_bookings:,.0f} nights; "
                        f"modelled direct gain {scenario.estimated_gained_direct:,.0f} nights."
                    ),
                    assumption=(
                        f"Depends entirely on the stated assumptions: conversion rates "
                        f"{assumptions_text(scenario.assumptions)}, max shift fraction "
                        f"{_pct(scenario.assumptions.max_shift_fraction)}. "
                        f"The allocator is a greedy heuristic, not a proven optimum."
                    ),
                    expected_impact=_inr(delta),
                    confidence="MEDIUM" if delta > 0 else "LOW",
                    evidence_type=SCENARIO_ASSUMPTION,
                    priority=70 if delta > 0 else 20,
                    channel_code=None,
                )
            )
        return out

    # -- helpers --------------------------------------------------------

    @staticmethod
    def _priority(materiality: Decimal) -> int:
        """Map materiality (0..1) to a 0..100 priority, deterministically."""
        scaled = int(materiality * Decimal("100"))
        return max(1, min(100, scaled))


def safe_share(part: Decimal, whole: Decimal) -> Decimal:
    if not whole:
        return Decimal("0")
    return quantize_rate(part / whole)


def assumptions_text(assumptions: Optional[ScenarioAssumptions]) -> str:
    if assumptions is None:
        return "n/a"
    parts = [
        f"{k} {_pct(v)}"
        for k, v in sorted(assumptions.expected_direct_conversion_rate.items())
        if v > 0
    ]
    return ", ".join(parts) if parts else "none supplied"